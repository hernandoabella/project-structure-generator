// ---------------------------------------------------------------------------
// Tree Preview Component (recursive-like, with connectors)
// ---------------------------------------------------------------------------

function TreePreview({ nodes }: { nodes: TreeNode[] }) {
  return (
    <div className="font-mono text-[13px] leading-6 select-text">
      {nodes.map((node, i) => {
        const isLast =
          i === nodes.length - 1 ||
          (i < nodes.length - 1 && nodes[i + 1].depth < node.depth);

        // Determine the connector lines for ancestors
        const segments: { char: string; active: boolean }[] = [];
        for (let d = 0; d < node.depth; d++) {
          // Check if any future node at this depth exists after this one
          let hasFutureSiblingAtDepth = false;
          for (let j = i + 1; j < nodes.length; j++) {
            if (nodes[j].depth === d) {
              hasFutureSiblingAtDepth = true;
              break;
            }
            if (nodes[j].depth < d) break;
          }
          segments.push({
            char: hasFutureSiblingAtDepth ? "│" : " ",
            active: hasFutureSiblingAtDepth,
          });
        }

        const connector = isLast ? "└── " : "├── ";

        return (
          <div
            key={`${node.path}-${i}`}
            className="flex items-center whitespace-nowrap"
          >
            {segments.map((seg, si) => (
              <span
                key={si}
                className={seg.active ? "text-zinc-600" : "text-transparent"}
              >
                {seg.char + "   "}
              </span>
            ))}
            <span className={node.type === "folder" ? "text-amber-400" : "text-zinc-500"}>
              {connector}
            </span>
            <span
              className={
                node.type === "folder"
                  ? "font-medium text-zinc-200"
                  : "text-zinc-400"
              }
            >
              {node.name}
            </span>
          </div>
        );
      })}
    </div>
  );
}

