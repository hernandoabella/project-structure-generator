// ---------------------------------------------------------------------------
// Types
// ---------------------------------------------------------------------------

type TreeNode = {
  name: string;
  path: string;
  type: "file" | "folder";
  /** Depth in the tree (root = 0) */
  depth: number;
};

// ---------------------------------------------------------------------------
// Tree Parser
// ---------------------------------------------------------------------------

const TREE_CONNECTORS = /[├└┌┐┘│─││├┤┬┴┼\u2502\u250c\u2510\u2514\u2518\u251c\u2524\u252c\u2534\u253c\u2500\u2520\u252e\u2530\u256c\u2528\u2560\u2561\u2562\u2563\u2564\u2565\u2566\u2567\u2568\u2569\u256a\u256b\u256d\u256e\u256f\u2570\u2571\u2572\u2573]/g;

/** Strip tree-drawing characters, comments, and whitespace from a name. */
function cleanName(raw: string): string {
  return raw
    .replace(/#.*$/, "")
    .replace(/--\s*$/, "")
    .replace(/`--\s*$/, "")
    .replace(TREE_CONNECTORS, "")
    .replace(/\t/g, "")
    .trim();
}

/**
 * Detect the tree prefix up to the connector character.
 * Handles: "│   ├──", "├──", "|   +--", "    └──", "  |--", etc.
 */
function parseLine(rawLine: string): { prefixLen: number; name: string } | null {
  // Match the connector part: optional prefix (pipes + spaces), then a
  // branching connector (├──, └──, |--, `--, +--, etc.), then the name.
  const m = rawLine.match(
    /^([\s│|]*)(?:[├└┌┐└┘]──|[|+]--|`--|--)\s*(.*)$/
  );
  if (m) {
    const name = cleanName(m[2]);
    if (!name) return null;
    return { prefixLen: m[1].length, name };
  }

  // Line with no connector but has leading pipes/spaces — could be a
  // continuation line; skip it or treat as empty.
  // If it's the very first line (root), it might just be a bare name.
  return null;
}

function parseTree(input: string): { nodes: TreeNode[]; warnings: string[] } {
  const lines = input.split("\n");
  const nodes: TreeNode[] = [];
  const warnings: string[] = [];
  const stack: { depth: number; prefixLen: number; path: string }[] = [];

  for (let i = 0; i < lines.length; i++) {
    const rawLine = lines[i];
    if (!rawLine.trim()) continue;

    const parsed = parseLine(rawLine);
    if (!parsed) {
      // Could be a bare root name on the first non-empty line
      if (nodes.length === 0) {
        const name = cleanName(rawLine);
        if (name) {
          nodes.push({ name, path: name, type: "folder", depth: 0 });
          stack.push({ depth: 0, prefixLen: 0, path: name });
        }
      }
      continue;
    }

    const { prefixLen, name } = parsed;

    // Infer depth from prefix length relative to known levels.
    // We find the stack entry whose prefixLen is closest but <= to this one.
    let depth = 0;
    while (
      stack.length > 1 &&
      stack[stack.length - 1].prefixLen >= prefixLen
    ) {
      stack.pop();
    }
    depth = stack.length;

    const parentPath =
      stack.length > 0 ? stack[stack.length - 1].path : "";
    const path = parentPath ? `${parentPath}/${name}` : name;

    const isFolder =
      name.endsWith("/") ||
      rawLine.trimEnd().endsWith("/") ||
      !/\.[a-zA-Z0-9]{1,15}$/.test(name);

    nodes.push({
      name: name.replace(/\/$/, ""),
      path,
      type: isFolder ? "folder" : "file",
      depth,
    });

    if (isFolder) {
      stack.push({ depth, prefixLen, path: path.replace(/\/$/, "") });
    }
  }

  if (nodes.length === 0) {
    warnings.push(
      "No valid tree entries found. Make sure you paste a directory tree format."
    );
  }

  return { nodes, warnings };
}

// ---------------------------------------------------------------------------
// Shell Script Generator
// ---------------------------------------------------------------------------

function generateShellScript(
  nodes: TreeNode[],
  projectName: string
): string {
  const lines: string[] = [
    "#!/bin/bash",
    "# Generated by ScaffoldForge",
    `# Project: ${projectName}`,
    "",
    `mkdir -p "${projectName}"`,
  ];

  for (const node of nodes) {
    if (node.type === "folder") {
      lines.push(`mkdir -p "${node.path}"`);
    } else {
      lines.push(`touch "${node.path}"`);
    }
  }

  lines.push("", `echo "✅ Project '${projectName}' created successfully!"`);
  return lines.join("\n");
}

// ---------------------------------------------------------------------------
// ZIP Generator
// ---------------------------------------------------------------------------

async function generateZip(
  nodes: TreeNode[],
  projectName: string
): Promise<Blob> {
  const zip = new JSZip();

  for (const node of nodes) {
    if (node.type === "folder") {
      zip.folder(node.path);
    } else {
      zip.file(node.path, "");
    }
  }

  return zip.generateAsync({ type: "blob", compression: "DEFLATE" });
}

